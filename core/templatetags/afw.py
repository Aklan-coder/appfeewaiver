from django import template
from django.utils.html import format_html

register = template.Library()

AVATAR_COLORS = ["bg-emerald-600", "bg-teal-600", "bg-sky-700", "bg-indigo-600", "bg-amber-600", "bg-rose-600", "bg-slate-600"]


@register.inclusion_tag("partials/avatar.html")
def avatar(user, size="md"):
    """Profile photo, or coloured initials when there is none."""
    photo_url = ""
    profile = getattr(user, "profile", None)
    if profile and profile.photo:
        try:
            photo_url = f"{profile.photo.url}?v={int(profile.updated_at.timestamp())}"
        except ValueError:
            photo_url = ""
    sizes = {"xs": "h-7 w-7 text-xs", "sm": "h-9 w-9 text-sm", "md": "h-11 w-11 text-base", "lg": "h-20 w-20 text-2xl", "xl": "h-28 w-28 text-4xl"}
    color = AVATAR_COLORS[(user.pk or 0) % len(AVATAR_COLORS)]
    return {"user": user, "photo_url": photo_url, "size_class": sizes.get(size, sizes["md"]), "color": color}


@register.simple_tag(takes_context=True)
def page_url(context, page_number):
    """Keep the current filters when linking to another page."""
    querystring = context.get("querystring", "")
    return f"?{querystring}&page={page_number}" if querystring else f"?page={page_number}"


@register.simple_tag(takes_context=True)
def filter_url(context, **changes):
    """Current query string with some parameters replaced (page is reset)."""
    params = context["request"].GET.copy()
    params.pop("page", None)
    for key, value in changes.items():
        if value in ("", None):
            params.pop(key, None)
        else:
            params[key] = value
    encoded = params.urlencode()
    return f"?{encoded}" if encoded else "?"


@register.filter
def in_set(value, collection):
    try:
        return value in (collection or ())
    except TypeError:
        return False


