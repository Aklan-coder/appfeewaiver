@register.simple_tag
def icon(name, css="h-5 w-5"):
    paths = ICONS.get(name, ICONS["info"])
    return format_html(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="{}" aria-hidden="true">{}</svg>',
        css,
        _safe(paths),
    )


def _safe(value):
    from django.utils.safestring import mark_safe

    return mark_safe(value)  # static, developer-defined SVG paths only


_STATIC_CACHE = {}


@register.simple_tag
def inline_static(path):
    """Return the contents of a static text file (used to inline CSS for the Tailwind CDN)."""
    from django.conf import settings
    from django.contrib.staticfiles import finders
    from django.utils.safestring import mark_safe

    if path not in _STATIC_CACHE or settings.DEBUG:
        found = finders.find(path)
        if not found:
            return ""
        with open(found, encoding="utf-8") as handle:
            _STATIC_CACHE[path] = handle.read()
    return mark_safe(_STATIC_CACHE[path])
